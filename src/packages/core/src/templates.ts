import type { AquaFilePlan, AquaProjectManifest } from './types.js';

export function renderProjectFiles(manifest: AquaProjectManifest): readonly AquaFilePlan[] {
  const files: AquaFilePlan[] = [
    file('.aqua/project.json', `${JSON.stringify(manifest, null, 2)}\n`),
    file('package.json', packageJson(manifest)),
    file('pnpm-workspace.yaml', 'packages: []\n'),
    file('tsconfig.json', tsconfigJson()),
    file('README.md', readme(manifest)),
    file('src/index.ts', indexTs()),
    file('src/harness/types.ts', harnessTypesTs()),
    file('src/harness/trace.ts', traceTs()),
    file('src/harness/artifacts.ts', artifactsTs()),
    file('src/harness/guardrails.ts', guardrailsTs()),
    file('src/harness/model-provider.ts', modelProviderTs()),
    file('src/harness/permissions.ts', permissionsTs()),
    file('src/harness/verification.ts', verificationTs()),
    file('src/harness/tools.ts', toolsTs(manifest)),
    file('src/harness/runner.ts', runnerTs()),
    file('src/workflows/plan-execute-verify.ts', workflowTs(manifest)),
    ...manifest.modules.agents.map((agent) => file(`src/agents/${agent}.ts`, agentTs(agent))),
    file('tests/fakes/fake-model-provider.ts', fakeModelProviderTs()),
    file('tests/smoke.test.ts', smokeTestTs(manifest)),
  ];

  if (manifest.modules.tools.includes('artifact-recorder')) {
    files.push(file('src/tools/artifact-recorder.ts', artifactRecorderToolTs()));
  }

  return files;
}

function file(relativePath: string, content: string): AquaFilePlan {
  return { relativePath, content };
}

