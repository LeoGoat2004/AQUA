function artifactWriterToolTs(): string {
  return `import type { Tool } from '../harness/types.js';

export const artifactWriterTool: Tool = {
  id: 'artifact-writer',
  description: 'Write an in-memory artifact for downstream inspection.',
  sideEffect: 'local-filesystem',
  async execute(input, context) {
    const permission = context.permissions.check({
      toolId: 'artifact-writer',
      sideEffect: 'local-filesystem',
      reason: 'The workflow requested an artifact write.',
    });
    if (!permission.allowed) {
      throw new Error(permission.reason);
    }
    const content = typeof input === 'string' ? input : JSON.stringify(input, null, 2);
    context.artifacts.write('artifact.txt', content);
    return { path: 'artifact.txt' };
  },
};
`;
}

function agentTs(agent: string): string {
  return `import type { Agent } from '../harness/types.js';

export const ${toExportedAgent(agent)}: Agent = {
  id: '${agent}',
  async run(input, context) {
    const echo = context.tools.get('echo');
    const echoed = echo ? await echo.execute(input, context) : input;
    return {
      success: true,
      output: \`[${agent}] \${String(echoed)}\`,
    };
  },
};
`;
}

function smokeTestTs(manifest: AquaProjectManifest): string {
  return `import test from 'node:test';
import assert from 'node:assert/strict';
import { run } from '../src/index.js';

test('${manifest.projectName} smoke workflow returns verified output and trace', async () => {
  const result = await run('hello');
  assert.equal(result.success, true);
  assert.match(result.output, /hello/);
  assert.ok(result.trace.some((event) => event.type === 'verification.completed'));
});
`;
}

function toExportedAgent(value: string): string {
  return `${toIdentifier(value)}Agent`;
}

function toIdentifier(value: string): string {
  const pascal = value.replace(/(^|[-_])([a-zA-Z0-9])/g, (_match, _prefix: string, char: string) => char.toUpperCase());
  return pascal.replace(/^[A-Z]/, (char) => char.toLowerCase());
}
