function permissionsTs(): string {
  return `import type { PermissionPolicy } from './types.js';

export function createDefaultPermissionPolicy(): PermissionPolicy {
  return {
    check(request) {
      if (request.sideEffect === 'none') {
        return { allowed: true, reason: 'Pure tool execution is allowed.' };
      }
      return {
        allowed: false,
        reason: \`Tool \${request.toolId} requires explicit permission for side effect: \${request.sideEffect}.\`,
      };
    },
  };
}
`;
}

