function smokeTestTs(manifest: AquaProjectManifest): string {
  return `import test from 'node:test';
import assert from 'node:assert/strict';
import { run } from '../src/index.js';
import { createFakeModelProvider } from './fakes/fake-model-provider.js';

test('${manifest.projectName} fails honestly without a configured model provider', async () => {
  const result = await run('hello');
  assert.equal(result.success, false);
  assert.equal(result.errorCode, 'MODEL_PROVIDER_NOT_CONFIGURED');
});

test('${manifest.projectName} harness runs with an explicit test model provider', async () => {
  const result = await run('hello', { modelProvider: createFakeModelProvider() });
  assert.equal(result.success, true);
  assert.match(result.output, /verified-test-output/);
  assert.ok(result.trace.some((event) => event.type === 'verification.completed'));
});
`;
}

function toExportedAgent(value: string): string {
  return `${toIdentifier(value)}Agent`;
}

function toIdentifier(value: string): string {
  const pascal = value.replace(/(^|[-_])([a-zA-Z0-9])/g, (_match, _prefix: string, char: string) => char.toUpperCase());
  return pascal.replace(/^[A-Z]/, (char) => char.toLowerCase());
}
